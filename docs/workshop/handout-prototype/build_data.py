"""PROTOTYPE: the chart data for the workshop help sheet prototype, written to data.js beside this file.

Run from the repository root: .venv/bin/python docs/workshop/handout-prototype/build_data.py
"""

import json
import pickle
from pathlib import Path

import numpy as np

from energetica.workshop.facilities import FacilityId
from energetica.workshop.seasons import SEASONS, representative_week, season_days
from energetica.workshop.weather import RunWeather

ROOT = Path(__file__).resolve().parents[3]
OUT = Path(__file__).with_name("data.js")

# Demand as a share of the yearly average, one row of 96 quarter-hours per day.
demand = np.asarray(pickle.load(open(ROOT / "src/energetica/workshop/data/national_demand_year_15min.pck", "rb")))
demand = demand.reshape(364, 96) / demand.mean()
daily_mean = demand.mean(1)
padded = np.concatenate([daily_mean[-7:], daily_mean, daily_mean[:7]])
smooth = np.convolve(padded, np.ones(15) / 15, "valid")
week_days = representative_week("winter")

out = {
    "daily_min": demand.min(1).round(3).tolist(),
    "daily_max": demand.max(1).round(3).tolist(),
    "smooth": smooth.round(3).tolist(),
    "week_days": week_days,
    "week_hourly": demand[week_days].reshape(-1, 4).mean(1).round(3).tolist(),
    "seasons": {season: [season_days(season)[0], season_days(season)[-1]] for season in SEASONS},
}

# Average share of maximum power per month. Wind and solar average 4 weather seeds; hydro follows a fixed table.
month = np.arange(364) * 12 // 364
for name, facility in {
    "wind": FacilityId.ONSHORE_WIND_TURBINE,
    "solar": FacilityId.PV_SOLAR,
    "hydro": FacilityId.SMALL_WATER_DAM,
}.items():
    seeds = [0] if name == "hydro" else range(4)
    daily = np.zeros(364)
    for seed in seeds:
        weather = RunWeather(seed=seed)
        daily += [np.mean([weather.share(facility, day * 86400 + h * 3600) for h in range(24)]) for day in range(364)]
    daily /= len(seeds)
    out[name] = [round(float(daily[month == m].mean()), 3) for m in range(12)]

OUT.write_text("// Generated by build_data.py. Do not edit.\nconst DATA = " + json.dumps(out) + ";\n")
