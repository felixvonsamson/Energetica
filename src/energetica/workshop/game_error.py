    WORKSHOP_NO_PHASE_RUNNING = "WORKSHOP_NO_PHASE_RUNNING"
    WORKSHOP_INVESTMENT_CLOSED = "WORKSHOP_INVESTMENT_CLOSED"
    WORKSHOP_FACILITY_NOT_OFFERED = "WORKSHOP_FACILITY_NOT_OFFERED"
    WORKSHOP_NOT_ENOUGH_MONEY = "WORKSHOP_NOT_ENOUGH_MONEY"
    WORKSHOP_FACILITY_LIMIT_REACHED = "WORKSHOP_FACILITY_LIMIT_REACHED"
    WORKSHOP_NOT_SELECTED = "WORKSHOP_NOT_SELECTED"
    WORKSHOP_PRICE_SETTING_CLOSED = "WORKSHOP_PRICE_SETTING_CLOSED"
    WORKSHOP_PRICE_BELOW_FLOOR = "WORKSHOP_PRICE_BELOW_FLOOR"
    WORKSHOP_PRICE_ABOVE_CEILING = "WORKSHOP_PRICE_ABOVE_CEILING"
    WORKSHOP_NOT_STORAGE = "WORKSHOP_NOT_STORAGE"
    WORKSHOP_FUEL_NOT_MANUAL = "WORKSHOP_FUEL_NOT_MANUAL"
    WORKSHOP_FUEL_NOT_BURNED = "WORKSHOP_FUEL_NOT_BURNED"
    WORKSHOP_SETTLEMENT_RUNNING = "WORKSHOP_SETTLEMENT_RUNNING"
    WORKSHOP_ROUND_LOCKED = "WORKSHOP_ROUND_LOCKED"
    WORKSHOP_LEVERS_INVALID = "WORKSHOP_LEVERS_INVALID"
    WORKSHOP_NO_EVENTS_IN_ROUND_ONE = "WORKSHOP_NO_EVENTS_IN_ROUND_ONE"
    WORKSHOP_RECAP_NOT_OPEN = "WORKSHOP_RECAP_NOT_OPEN"
    WORKSHOP_SESSION_NOT_FINISHED = "WORKSHOP_SESSION_NOT_FINISHED"
    WORKSHOP_NO_VOTE = "WORKSHOP_NO_VOTE"
    WORKSHOP_NO_VOTE_IN_ROUND_ONE = "WORKSHOP_NO_VOTE_IN_ROUND_ONE"
    WORKSHOP_CARBON_TAX_PASSED = "WORKSHOP_CARBON_TAX_PASSED"
    WORKSHOP_NO_SUCH_ROUND = "WORKSHOP_NO_SUCH_ROUND"
    WORKSHOP_INVALID_PICK = "WORKSHOP_INVALID_PICK"
    WORKSHOP_INVALID_FUEL_QUANTITY = "WORKSHOP_INVALID_FUEL_QUANTITY"
    WORKSHOP_NO_PERIOD_RECORD = "WORKSHOP_NO_PERIOD_RECORD"
